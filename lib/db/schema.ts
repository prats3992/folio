import { relations, sql } from "drizzle-orm"
import {
  bigint,
  boolean,
  date,
  index,
  integer,
  jsonb,
  pgTable,
  primaryKey,
  text,
  timestamp,
  uniqueIndex,
} from "drizzle-orm/pg-core"
import type { UIMessage } from "ai"
import type { ResumeData } from "@/lib/resume/schema"
import type {
  BehavioralQuestion,
  DsaChallengePublic,
  JobAnalysisResult,
} from "@/lib/ai/schemas"

const id = () =>
  text("id")
    .primaryKey()
    .$defaultFn(() => crypto.randomUUID())

const timestamps = {
  createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
  updatedAt: timestamp("updated_at", { withTimezone: true })
    .notNull()
    .defaultNow()
    .$onUpdate(() => new Date()),
}

// ---------------------------------------------------------------------------
// Better Auth core tables
// ---------------------------------------------------------------------------

export const user = pgTable("user", {
  id: text("id").primaryKey(),
  name: text("name").notNull(),
  email: text("email").notNull().unique(),
  emailVerified: boolean("email_verified").notNull().default(false),
  image: text("image"),
  // additional fields (declared in lib/auth.ts)
  plan: text("plan", { enum: ["free", "basic", "premium"] }).notNull().default("free"),
  dsaSkillLevel: text("dsa_skill_level", {
    enum: ["beginner", "intermediate", "advanced", "expert"],
  })
    .notNull()
    .default("beginner"),
  primaryResumeId: text("primary_resume_id"),
  ...timestamps,
})

export const session = pgTable(
  "session",
  {
    id: text("id").primaryKey(),
    expiresAt: timestamp("expires_at", { withTimezone: true }).notNull(),
    token: text("token").notNull().unique(),
    ipAddress: text("ip_address"),
    userAgent: text("user_agent"),
    userId: text("user_id")
      .notNull()
      .references(() => user.id, { onDelete: "cascade" }),
    ...timestamps,
  },
  (t) => [index("session_user_idx").on(t.userId)],
)

export const account = pgTable(
  "account",
  {
    id: text("id").primaryKey(),
    accountId: text("account_id").notNull(),
    providerId: text("provider_id").notNull(),
    userId: text("user_id")
      .notNull()
      .references(() => user.id, { onDelete: "cascade" }),
    accessToken: text("access_token"),
    refreshToken: text("refresh_token"),
    idToken: text("id_token"),
    accessTokenExpiresAt: timestamp("access_token_expires_at", { withTimezone: true }),
    refreshTokenExpiresAt: timestamp("refresh_token_expires_at", { withTimezone: true }),
    scope: text("scope"),
    password: text("password"),
    ...timestamps,
  },
  (t) => [index("account_user_idx").on(t.userId)],
)

export const verification = pgTable(
  "verification",
  {
    id: text("id").primaryKey(),
    identifier: text("identifier").notNull(),
    value: text("value").notNull(),
    expiresAt: timestamp("expires_at", { withTimezone: true }).notNull(),
    ...timestamps,
  },
  (t) => [index("verification_identifier_idx").on(t.identifier)],
)

// Better Auth's rate limiter (storage: "database") — counts survive serverless cold starts
export const rateLimit = pgTable("rate_limit", {
  id: text("id").primaryKey(),
  key: text("key").notNull().unique(),
  count: integer("count").notNull(),
  lastRequest: bigint("last_request", { mode: "number" }).notNull(),
})

// ---------------------------------------------------------------------------
// App tables
// ---------------------------------------------------------------------------

export const resume = pgTable(
  "resume",
  {
    id: id(),
    userId: text("user_id")
      .notNull()
      .references(() => user.id, { onDelete: "cascade" }),
    title: text("title").notNull(),
    targetRole: text("target_role").notNull().default(""),
    template: text("template").notNull().default("minimal"),
    data: jsonb("data").$type<ResumeData>().notNull(),
    sourceText: text("source_text"),
    isPublic: boolean("is_public").notNull().default(false),
    shareSlug: text("share_slug"),
    ...timestamps,
  },
  (t) => [
    index("resume_user_idx").on(t.userId),
    uniqueIndex("resume_share_slug_idx").on(t.shareSlug),
  ],
)

export const chat = pgTable(
  "chat",
  {
    id: id(),
    userId: text("user_id")
      .notNull()
      .references(() => user.id, { onDelete: "cascade" }),
    resumeId: text("resume_id").references(() => resume.id, { onDelete: "set null" }),
    title: text("title").notNull(),
    kind: text("kind", { enum: ["general", "resume_review", "mock_interview"] })
      .notNull()
      .default("general"),
    meta: jsonb("meta").$type<{ targetRole?: string }>().notNull().default({}),
    ...timestamps,
  },
  (t) => [index("chat_user_idx").on(t.userId, t.updatedAt)],
)

export const message = pgTable(
  "message",
  {
    // UIMessage ids are generated by the AI SDK (client for user turns, server for assistant)
    id: text("id").primaryKey(),
    chatId: text("chat_id")
      .notNull()
      .references(() => chat.id, { onDelete: "cascade" }),
    role: text("role", { enum: ["system", "user", "assistant"] }).notNull(),
    parts: jsonb("parts").$type<UIMessage["parts"]>().notNull(),
    createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
  },
  (t) => [index("message_chat_idx").on(t.chatId, t.createdAt)],
)

export const jobAnalysis = pgTable(
  "job_analysis",
  {
    id: id(),
    userId: text("user_id")
      .notNull()
      .references(() => user.id, { onDelete: "cascade" }),
    resumeId: text("resume_id").references(() => resume.id, { onDelete: "set null" }),
    jobTitle: text("job_title").notNull().default(""),
    jobDescription: text("job_description").notNull(),
    result: jsonb("result").$type<JobAnalysisResult>().notNull(),
    createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
  },
  (t) => [index("job_analysis_user_idx").on(t.userId, t.createdAt)],
)

export const behavioralSet = pgTable(
  "behavioral_set",
  {
    id: id(),
    userId: text("user_id")
      .notNull()
      .references(() => user.id, { onDelete: "cascade" }),
    resumeId: text("resume_id").references(() => resume.id, { onDelete: "set null" }),
    jobTitle: text("job_title").notNull(),
    questions: jsonb("questions").$type<BehavioralQuestion[]>().notNull(),
    createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
  },
  (t) => [index("behavioral_set_user_idx").on(t.userId, t.createdAt)],
)

export const dsaChallenge = pgTable(
  "dsa_challenge",
  {
    id: id(),
    userId: text("user_id")
      .notNull()
      .references(() => user.id, { onDelete: "cascade" }),
    skillLevel: text("skill_level").notNull(),
    // problem statement + hints (hints are revealed one at a time via revealHint)
    challenge: jsonb("challenge").$type<DsaChallengePublic>().notNull(),
    // server-only until the user submits
    solution: text("solution").notNull(),
    explanation: text("explanation").notNull(),
    userSolution: text("user_solution"),
    success: boolean("success"),
    feedback: text("feedback"),
    timeSpentSec: integer("time_spent_sec"),
    hintsUsed: integer("hints_used").notNull().default(0),
    score: integer("score"),
    createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
    submittedAt: timestamp("submitted_at", { withTimezone: true }),
  },
  (t) => [index("dsa_challenge_user_idx").on(t.userId, t.createdAt)],
)

export const feedback = pgTable(
  "feedback",
  {
    id: id(),
    userId: text("user_id").references(() => user.id, { onDelete: "set null" }),
    title: text("title").notNull(),
    experience: text("experience").notNull(),
    feature: text("feature").notNull(),
    sentiment: text("sentiment", { enum: ["positive", "neutral", "negative"] }).notNull(),
    name: text("name").notNull(),
    role: text("role").notNull(),
    company: text("company").notNull(),
    // set to false in the DB to hide an entry from the public reviews page
    isApproved: boolean("is_approved").notNull().default(true),
    createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
  },
  (t) => [index("feedback_approved_idx").on(t.isApproved, t.createdAt)],
)

export const aiUsage = pgTable(
  "ai_usage",
  {
    userId: text("user_id")
      .notNull()
      .references(() => user.id, { onDelete: "cascade" }),
    day: date("day", { mode: "string" }).notNull().default(sql`current_date`),
    count: integer("count").notNull().default(0),
  },
  (t) => [primaryKey({ columns: [t.userId, t.day] })],
)

/** Fixed-window counters for app-level limits (AI bursts, uploads, resource creation). */
export const appRateLimit = pgTable("app_rate_limit", {
  key: text("key").primaryKey(),
  windowStart: timestamp("window_start", { withTimezone: true }).notNull().defaultNow(),
  count: integer("count").notNull().default(0),
})

// ---------------------------------------------------------------------------
// Relations
// ---------------------------------------------------------------------------

export const userRelations = relations(user, ({ many }) => ({
  resumes: many(resume),
  chats: many(chat),
}))

export const resumeRelations = relations(resume, ({ one }) => ({
  user: one(user, { fields: [resume.userId], references: [user.id] }),
}))

export const chatRelations = relations(chat, ({ one, many }) => ({
  user: one(user, { fields: [chat.userId], references: [user.id] }),
  resume: one(resume, { fields: [chat.resumeId], references: [resume.id] }),
  messages: many(message),
}))

export const messageRelations = relations(message, ({ one }) => ({
  chat: one(chat, { fields: [message.chatId], references: [chat.id] }),
}))
